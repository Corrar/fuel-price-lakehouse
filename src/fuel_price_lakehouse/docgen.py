"""Documents generated from the code, so they cannot drift from what runs.

Each function renders one Markdown document from the objects the pipeline
uses. The rendered files are committed under ``docs/``, and a test fails when
a committed file differs from what the code renders now: change a rule, run
``make docs``, commit both.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

from fuel_price_lakehouse.stage.rules import Rule, Severity

GENERATED_NOTE = "<!-- Generated by `make docs` from the code. Do not edit by hand. -->"


def quality_rules() -> str:
    """The row-level validation rules of every source, with severities and descriptions."""
    from fuel_price_lakehouse.stage import anp, bcb_sgs

    sections = [
        ("ANP — station-level fuel prices", anp.RULES),
        ("Banco Central do Brasil — SGS series", bcb_sgs.RULES),
    ]
    lines = [
        GENERATED_NOTE,
        "",
        "# Row-level quality rules",
        "",
        "Every raw row is judged by the rules of its source when it is staged.",
        "",
        "- **error**: the row cannot be trusted. It goes to the quarantine layer, with",
        "  the original text of every field and the ids of every error rule it broke,",
        "  and never reaches the staged layer.",
        "- **warning**: the row is kept, and the rule id is recorded on it.",
        "",
        "Each description says what a valid row looks like. The ids are stored in the",
        "quarantine files and counted in the quality report on the dashboard; the",
        "decisions behind them are in",
        "[ADR 0003](decisions/0003-validation-and-quarantine.md).",
    ]
    for title, rules in sections:
        lines += ["", f"## {title}", "", *_rules_table(rules)]
    return "\n".join(lines) + "\n"


def _rules_table(rules: Sequence[Rule]) -> list[str]:
    ordered = sorted(rules, key=lambda rule: rule.severity is not Severity.ERROR)
    rows = [
        "| Rule | Severity | A valid row... | Uma linha válida... |",
        "| --- | --- | --- | --- |",
    ]
    rows += [
        f"| `{rule.id}` | {rule.severity} | {rule.description} | {rule.description_pt} |"
        for rule in ordered
    ]
    return rows


DOCUMENTS = {"docs/quality-rules.md": quality_rules}
"""Every generated document, by its path relative to the repository root."""


def write_all(repository: Path) -> list[Path]:
    """Render every generated document into the repository. Returns the paths written."""
    written = []
    for relative, render in DOCUMENTS.items():
        path = repository / relative
        path.write_text(render(), encoding="utf-8")
        written.append(path)
    return written
